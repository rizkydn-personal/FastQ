#!/bin/sh
set -eu
: "${POS_APP_PASSWORD:?POS_APP_PASSWORD wajib diatur}"
: "${POS_ADMIN_PASSWORD:?POS_ADMIN_PASSWORD wajib diatur}"
: "${POSTGRES_PASSWORD:?POSTGRES_PASSWORD wajib diatur}"
[ "$POS_ADMIN_PASSWORD" != "$POSTGRES_PASSWORD" ] || { echo "POS_ADMIN_PASSWORD harus berbeda dari POSTGRES_PASSWORD" >&2; exit 1; }
[ "$POS_APP_PASSWORD" != "$POS_ADMIN_PASSWORD" ] || { echo "POS_APP_PASSWORD harus berbeda dari POS_ADMIN_PASSWORD" >&2; exit 1; }
[ "$POS_APP_PASSWORD" != "$POSTGRES_PASSWORD" ] || { echo "POS_APP_PASSWORD harus berbeda dari POSTGRES_PASSWORD" >&2; exit 1; }
bootstrap_user=${POS_BOOTSTRAP_USER:-$POSTGRES_USER}

psql --username "$bootstrap_user" --dbname "$POSTGRES_DB" \
  --set=ON_ERROR_STOP=1 --set=app_password="$POS_APP_PASSWORD" --set=admin_password="$POS_ADMIN_PASSWORD" <<'SQL'
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='pos_admin') THEN
    CREATE ROLE pos_admin LOGIN SUPERUSER;
  END IF;
END $$;
ALTER ROLE pos_admin WITH LOGIN SUPERUSER PASSWORD :'admin_password';

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='pos_app') THEN
    CREATE ROLE pos_app LOGIN;
  END IF;
END $$;
ALTER ROLE pos_app WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'app_password';

REASSIGN OWNED BY pos_app TO pos_admin;
ALTER DATABASE pos OWNER TO pos_admin;
GRANT CONNECT ON DATABASE pos TO pos_app;
GRANT USAGE ON SCHEMA public TO pos_app;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA public TO pos_app;
GRANT USAGE,SELECT,UPDATE ON ALL SEQUENCES IN SCHEMA public TO pos_app;
REVOKE INSERT,UPDATE,DELETE ON TABLE schema_migrations FROM pos_app;
ALTER DEFAULT PRIVILEGES FOR ROLE pos_admin IN SCHEMA public
  GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO pos_app;
ALTER DEFAULT PRIVILEGES FOR ROLE pos_admin IN SCHEMA public
  GRANT USAGE,SELECT,UPDATE ON SEQUENCES TO pos_app;
ALTER ROLE pos_admin WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'admin_password';
SQL
